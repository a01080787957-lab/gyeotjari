'use client';
import { useEffect, useState } from 'react';
import { supabase } from '../../lib/supabase';

export default function Privacy() {
  const [c, setC] = useState({});
  useEffect(() => {
    supabase.from('site_settings').select('key,value').in('key', ['biz_name', 'biz_owner', 'biz_email', 'biz_officer', 'phone'])
      .then(({ data }) => setC(Object.fromEntries((data || []).map((r) => [r.key, r.value]))));
  }, []);
  const v = (k) => c[k] || '(운영자가 입력 예정)';
  return (
    <div className="adm doc">
      <h1>개인정보 처리방침</h1>
      <p className="muted">시행일: 2026년 9월 30일</p>
      <p>「곁자리」(이하 "곁자리")는 이용자의 개인정보를 소중히 다루며, 아래와 같이 개인정보를 처리합니다.</p>

      <h3>1. 수집하는 개인정보 항목</h3>
      <ul>
        <li>회원가입: 이름, 전화번호, 이메일, 비밀번호(암호화되어 저장). 소셜 로그인 시 해당 서비스가 제공하는 이름·이메일</li>
        <li>예약: 이름, 전화번호, 지역, 상세 주소, 요청 내용, 희망 일시</li>
        <li>채팅 상담: 대화 내용과 이용자가 직접 보낸 사진</li>
        <li>서비스 이용 중 자동 생성: 접속 기록, 브라우저 저장소(로그인 유지용)</li>
      </ul>

      <h3>2. 이용 목적</h3>
      <ul>
        <li>회원 식별과 로그인 유지</li>
        <li>예약 접수, 상담, 서비스 제공, 견적과 결과 안내</li>
        <li>문의 응대와 분쟁 처리, 서비스 개선</li>
      </ul>

      <h3>3. 보유 및 이용 기간</h3>
      <p>회원 탈퇴 또는 삭제 요청 시까지 보유하고 지체 없이 파기합니다. 다만 계약·청약철회, 대금 결제, 소비자 분쟁 처리 등 관계 법령에 따라 보관이 필요한 정보는 해당 법령이 정한 기간 동안 보관합니다.</p>

      <h3>4. 제3자 제공</h3>
      <p>곁자리는 이용자의 동의 없이 개인정보를 제3자에게 제공하지 않습니다. 법령에 근거가 있는 경우는 예외로 합니다.</p>

      <h3>5. 처리 위탁 및 국외 이전</h3>
      <p>안정적인 서비스 제공을 위해 아래 업체에 개인정보 처리를 맡기고 있습니다.</p>
      <ul>
        <li>Supabase: 회원 인증, 데이터베이스와 사진 저장 (데이터는 서울 리전에 저장)</li>
        <li>Cloudflare: 웹사이트 호스팅</li>
        <li>Resend: 새 예약과 상담 알림 이메일 발송 (운영자에게 전달되는 알림에 이름, 연락처, 주소가 포함될 수 있음)</li>
        <li>Google, Kakao: 소셜 로그인을 이용하는 경우에 한해 인증 처리</li>
      </ul>
      <p>위 업체 중 일부는 해외에 서버를 두고 있어 개인정보가 국외로 이전·처리될 수 있습니다.</p>

      <h3>6. 이용자의 권리</h3>
      <p>이용자는 언제든지 개인정보의 열람, 정정, 삭제, 처리 정지와 동의 철회를 요청할 수 있습니다. 이름과 전화번호는 마이페이지에서 직접 수정할 수 있고, 삭제 등 그 밖의 요청은 아래 연락처로 알려 주세요.</p>

      <h3>7. 개인정보의 파기</h3>
      <p>보유 기간이 지나거나 목적이 달성된 개인정보는 복구할 수 없는 방법으로 삭제합니다.</p>

      <h3>8. 안전성 확보 조치</h3>
      <ul>
        <li>비밀번호는 인증 서비스가 암호화하여 저장하며 곁자리는 원문을 알 수 없습니다.</li>
        <li>데이터베이스 접근 통제를 적용하여 이용자는 본인의 예약과 채팅만 볼 수 있습니다.</li>
        <li>채팅 사진은 비공개 저장소에 보관되며 본인과 운영자만 열람할 수 있습니다.</li>
        <li>모든 통신은 암호화(HTTPS)됩니다.</li>
      </ul>

      <h3>9. 브라우저 저장소</h3>
      <p>로그인 상태를 유지하기 위해 브라우저 저장소를 사용합니다. 브라우저 설정에서 삭제할 수 있으나 이 경우 다시 로그인해야 합니다.</p>

      <h3>10. 사업자 정보 및 개인정보 보호책임자</h3>
      <ul>
        <li>상호: {v('biz_name')}</li>
        <li>대표자: {v('biz_owner')}</li>
        <li>개인정보 보호책임자: {v('biz_officer')}</li>
        <li>문의 이메일: {v('biz_email')}</li>
        <li>전화: {v('phone')}</li>
      </ul>

      <h3>11. 방침의 변경</h3>
      <p>이 방침이 바뀌면 시행 전에 사이트에 공지합니다.</p>
    </div>
  );
}
